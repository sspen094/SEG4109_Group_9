"""Data access layer: SQLite persistence for feedback, staff overrides,
settings, user accounts and the collection run log."""
import hashlib
import os
import re
import sqlite3
from datetime import date, datetime, timedelta

from werkzeug.security import check_password_hash, generate_password_hash

from trfd import tagging

DEFAULT_DB = os.environ.get("TRFD_DB", "trfd.db")

SCHEMA = """
CREATE TABLE IF NOT EXISTS feedback (
    id           INTEGER PRIMARY KEY AUTOINCREMENT,
    source       TEXT NOT NULL,
    posted_at    TEXT NOT NULL,
    text         TEXT NOT NULL,
    sentiment    TEXT NOT NULL,
    confidence   REAL NOT NULL,
    route        TEXT,
    stop         TEXT,
    category     TEXT NOT NULL,
    needs_review INTEGER NOT NULL,
    fingerprint  TEXT,
    origin       TEXT NOT NULL DEFAULT 'sample'
);
CREATE TABLE IF NOT EXISTS override_log (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    feedback_id INTEGER NOT NULL REFERENCES feedback(id),
    field       TEXT NOT NULL,
    old_value   TEXT,
    new_value   TEXT,
    changed_at  TEXT DEFAULT CURRENT_TIMESTAMP,
    changed_by  TEXT
);
CREATE TABLE IF NOT EXISTS settings (
    key   TEXT PRIMARY KEY,
    value TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS users (
    id            INTEGER PRIMARY KEY AUTOINCREMENT,
    username      TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role          TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS runs (
    id          INTEGER PRIMARY KEY AUTOINCREMENT,
    kind        TEXT NOT NULL,
    started_at  TEXT NOT NULL,
    finished_at TEXT,
    status      TEXT NOT NULL DEFAULT 'running',
    stored      INTEGER,
    alerts      INTEGER,
    message     TEXT
);
"""
INDEXES = """
CREATE UNIQUE INDEX IF NOT EXISTS feedback_fingerprint ON feedback(fingerprint);
CREATE INDEX IF NOT EXISTS feedback_posted_at ON feedback(posted_at);
CREATE INDEX IF NOT EXISTS feedback_route ON feedback(route);
"""
FILTERS = ("source", "sentiment", "route", "stop", "category")
EDITABLE = ("sentiment", "route", "stop", "category")
SENTIMENTS = ("negative", "neutral", "positive")
ROLES = ("executive", "staff", "admin")
SOURCES = ("reddit", "app_store", "google_maps")

DEFAULT_DEMO_PASSWORD = "trfd-demo"
DEMO_PASSWORD = os.environ.get("TRFD_DEMO_PASSWORD", DEFAULT_DEMO_PASSWORD)
DEFAULT_SETTINGS = {
    "alert_threshold": os.environ.get("TRFD_ALERT_THRESHOLD", "3"),
    "alert_window_days": "30",
    "sources_enabled": ",".join(SOURCES),
}


def connect(db_path=None):
    conn = sqlite3.connect(db_path or DEFAULT_DB, timeout=10)
    conn.row_factory = sqlite3.Row
    conn.executescript(SCHEMA)
    _migrate(conn)
    conn.executescript(INDEXES)
    _seed_users(conn)
    return conn


def _columns(conn, table):
    return {r[1] for r in conn.execute(f"PRAGMA table_info({table})")}


def _migrate(conn):
    """Upgrade databases created by the first prototype (Lab 8)."""
    if "fingerprint" not in _columns(conn, "feedback"):
        # The first prototype rebuilt this table from the sample data on every
        # cycle, so the old rows are regenerated by the next cycle.
        conn.execute("DELETE FROM feedback")
        conn.execute("ALTER TABLE feedback ADD COLUMN fingerprint TEXT")
    if "origin" not in _columns(conn, "feedback"):
        conn.execute("ALTER TABLE feedback ADD COLUMN origin TEXT NOT NULL DEFAULT 'sample'")
    if "changed_by" not in _columns(conn, "override_log"):
        conn.execute("ALTER TABLE override_log ADD COLUMN changed_by TEXT")
    conn.commit()


def _now():
    return datetime.now().isoformat(timespec="seconds")


def fingerprint(text):
    return hashlib.sha256(re.sub(r"[^a-z0-9]", "", text.lower()).encode()).hexdigest()


# ---- Feedback ----------------------------------------------------------------

def save(conn, records):
    """Insert new records. Items already stored (same text fingerprint) are
    skipped, so staff overrides survive later collection cycles."""
    before = conn.total_changes
    conn.executemany(
        "INSERT OR IGNORE INTO feedback (source, posted_at, text, sentiment, confidence,"
        " route, stop, category, needs_review, fingerprint, origin) VALUES (:source,"
        " :posted_at, :text, :sentiment, :confidence, :route, :stop, :category,"
        " :needs_review, :fingerprint, :origin)",
        [dict(r, fingerprint=fingerprint(r["text"]), origin=r.get("origin", "sample"))
         for r in records])
    conn.commit()
    return conn.total_changes - before


def remove_sample(conn, source, keep=frozenset()):
    """Remove a source's sample-dataset items except those whose fingerprint is
    in keep: all of them once live data replaces the source, or the ones no
    longer in the sample file. Returns the number of items removed."""
    stale = [r["id"] for r in conn.execute(
        "SELECT id, fingerprint FROM feedback WHERE source = ? AND origin = 'sample'",
        (source,)) if r["fingerprint"] not in keep]
    for item_id in stale:
        conn.execute("DELETE FROM override_log WHERE feedback_id = ?", (item_id,))
        conn.execute("DELETE FROM feedback WHERE id = ?", (item_id,))
    conn.commit()
    return len(stale)


def retag(conn):
    """Re-run tagging on items staff have not changed, so stored tags follow a
    new route and station list (a newer GTFS feed). The stored station is
    passed as a hint, because collector hints themselves are not stored."""
    touched = {r[0] for r in conn.execute("SELECT DISTINCT feedback_id FROM override_log")}
    changed = 0
    for r in conn.execute("SELECT * FROM feedback").fetchall():
        if r["id"] in touched:
            continue
        tags = tagging.tag(r["text"], f"{r['stop']} station" if r["stop"] else None,
                           r["source"])
        new = (tags["route"], tags["stop"], tags["category"], int(tags["needs_review"]))
        if new != (r["route"], r["stop"], r["category"], r["needs_review"]):
            conn.execute("UPDATE feedback SET route = ?, stop = ?, category = ?,"
                         " needs_review = ? WHERE id = ?", (*new, r["id"]))
            changed += 1
    conn.commit()
    return changed


def _where(filters, *extra):
    """WHERE clause for the dashboard filters plus fixed extra conditions."""
    clauses, params = list(extra), []
    for key in FILTERS:
        if filters.get(key):
            clauses.append(f"{key} = ?")
            params.append(filters[key])
    if filters.get("needs_review"):
        clauses.append("needs_review = 1")
    if filters.get("q"):
        clauses.append("text LIKE ?")
        params.append(f"%{filters['q']}%")
    if str(filters.get("days") or "").isdigit() and int(filters["days"]) > 0:
        since = datetime.now() - timedelta(days=int(filters["days"]))
        clauses.append("posted_at >= ?")
        params.append(since.strftime("%Y-%m-%dT%H:%M:%S"))
    return (" WHERE " + " AND ".join(clauses) if clauses else ""), params


def query(conn, limit=None, **filters):
    where, params = _where(filters)
    sql = f"SELECT * FROM feedback{where} ORDER BY posted_at DESC, id DESC"
    if limit:
        sql += f" LIMIT {int(limit)}"
    return [dict(r) for r in conn.execute(sql, params)]


def count(conn, **filters):
    where, params = _where(filters)
    return conn.execute(f"SELECT COUNT(*) FROM feedback{where}", params).fetchone()[0]


def get(conn, feedback_id):
    row = conn.execute("SELECT * FROM feedback WHERE id = ?", (feedback_id,)).fetchone()
    return dict(row) if row else None


def history(conn, feedback_id):
    rows = conn.execute(
        "SELECT * FROM override_log WHERE feedback_id = ? ORDER BY id DESC", (feedback_id,))
    return [dict(r) for r in rows]


def hotspots(conn, **filters):
    """Negative feedback grouped by route and issue category, worst first."""
    where, params = _where(filters, "sentiment = 'negative'", "route IS NOT NULL")
    rows = conn.execute(
        f"SELECT route, category, COUNT(*) AS negative FROM feedback{where}"
        " GROUP BY route, category ORDER BY negative DESC, route", params)
    return [dict(r) for r in rows]


def stop_hotspots(conn, **filters):
    """Every stop with coordinates, with its total and negative item counts."""
    where, params = _where(filters, "stop IS NOT NULL")
    rows = conn.execute(
        f"SELECT stop, COUNT(*) AS total, SUM(sentiment = 'negative') AS negative"
        f" FROM feedback{where} GROUP BY stop", params)
    counts = {r["stop"]: dict(r) for r in rows}
    out = []
    for s in tagging.STOPS:
        if not (s.get("lat") and s.get("lon")):
            continue
        c = counts.get(s["stop_name"], {})
        out.append({"stop": s["stop_name"], "route": s["route_id"] or None,
                    "lines": (s.get("lines") or "").split(),
                    "lat": float(s["lat"]), "lon": float(s["lon"]),
                    "total": c.get("total", 0), "negative": c.get("negative") or 0})
    return out


def summary(conn, **filters):
    where, params = _where(filters)
    rows = conn.execute(
        f"SELECT sentiment, COUNT(*) AS n FROM feedback{where} GROUP BY sentiment", params)
    counts = dict.fromkeys(SENTIMENTS, 0) | {r["sentiment"]: r["n"] for r in rows}
    counts["total"] = sum(counts[s] for s in SENTIMENTS)
    counts["review_queue"] = count(conn, **dict(filters, needs_review=True))
    return counts


def trend(conn, **filters):
    """Sentiment counts per week, or per month when the data spans over 120 days.
    Empty periods are kept so the time axis has no gaps."""
    where, params = _where(filters)
    first, last = conn.execute(
        f"SELECT MIN(posted_at), MAX(posted_at) FROM feedback{where}", params).fetchone()
    if not first:
        return {"granularity": "week", "periods": [],
                "series": {s: [] for s in SENTIMENTS}}
    first, last = date.fromisoformat(first[:10]), date.fromisoformat(last[:10])
    monthly = (last - first).days > 120
    if monthly:
        bucket = "strftime('%Y-%m-01', posted_at)"
        periods, d = [], first.replace(day=1)
        while d <= last:
            periods.append(d.isoformat())
            d = (d + timedelta(days=32)).replace(day=1)
    else:
        bucket = "date(posted_at, '-6 days', 'weekday 1')"  # Monday of the week
        periods, d = [], first - timedelta(days=first.weekday())
        while d <= last:
            periods.append(d.isoformat())
            d += timedelta(days=7)
    index = {p: i for i, p in enumerate(periods)}
    series = {s: [0] * len(periods) for s in SENTIMENTS}
    rows = conn.execute(
        f"SELECT {bucket} AS period, sentiment, COUNT(*) AS n FROM feedback{where}"
        " GROUP BY period, sentiment", params)
    for r in rows:
        if r["period"] in index and r["sentiment"] in series:
            series[r["sentiment"]][index[r["period"]]] = r["n"]
    return {"granularity": "month" if monthly else "week", "periods": periods,
            "series": series}


def by_route(conn, limit=12, **filters):
    where, params = _where(filters, "route IS NOT NULL")
    rows = conn.execute(
        f"SELECT route, SUM(sentiment = 'negative') AS negative,"
        f" SUM(sentiment = 'neutral') AS neutral, SUM(sentiment = 'positive') AS positive,"
        f" COUNT(*) AS total FROM feedback{where} GROUP BY route"
        f" ORDER BY negative DESC, total DESC LIMIT {int(limit)}", params)
    return [dict(r, name=tagging.ROUTE_NAMES.get(r["route"], f"Route {r['route']}"))
            for r in rows]


def by_category(conn, **filters):
    where, params = _where(filters)
    rows = conn.execute(
        f"SELECT category, SUM(sentiment = 'negative') AS negative, COUNT(*) AS total"
        f" FROM feedback{where} GROUP BY category ORDER BY negative DESC, total DESC",
        params)
    return [dict(r) for r in rows]


def validate(changes):
    """Check a staff override. Returns the editable fields with blank route or
    stop turned into None; raises ValueError for a value outside the lists."""
    allowed = {"sentiment": set(SENTIMENTS), "category": set(tagging.CATEGORIES),
               "route": tagging.ROUTE_IDS, "stop": set(tagging.STOP_NAMES)}
    clean = {}
    for field in EDITABLE:
        if field not in changes:
            continue
        value = changes[field]
        if value is not None and not isinstance(value, str):
            raise ValueError(f"{field} must be text")
        value = (value or "").strip() or None
        if value is None and field in ("route", "stop"):
            clean[field] = None
        elif value not in allowed[field]:
            raise ValueError(f"Unknown {field}: {value}")
        else:
            clean[field] = value
    return clean


def override(conn, feedback_id, changes, user=None):
    """Apply a staff override and keep the old value for later retraining.
    Saving marks the item as reviewed, which takes it out of the manual queue."""
    row = get(conn, feedback_id)
    if row is None:
        return None
    for field, value in validate(changes).items():
        if value == row[field]:
            continue
        conn.execute(
            "INSERT INTO override_log (feedback_id, field, old_value, new_value, changed_by)"
            " VALUES (?, ?, ?, ?, ?)", (feedback_id, field, row[field], value, user))
        conn.execute(f"UPDATE feedback SET {field} = ? WHERE id = ?", (value, feedback_id))
        if field == "sentiment":  # a staff label is certain
            conn.execute("UPDATE feedback SET confidence = 1.0 WHERE id = ?", (feedback_id,))
    conn.execute("UPDATE feedback SET needs_review = 0 WHERE id = ?", (feedback_id,))
    conn.commit()
    return get(conn, feedback_id)


# ---- Settings ----------------------------------------------------------------

def get_setting(conn, key):
    row = conn.execute("SELECT value FROM settings WHERE key = ?", (key,)).fetchone()
    return row[0] if row else DEFAULT_SETTINGS.get(key)


def set_setting(conn, key, value):
    conn.execute(
        "INSERT INTO settings (key, value) VALUES (?, ?)"
        " ON CONFLICT(key) DO UPDATE SET value = excluded.value", (key, str(value)))
    conn.commit()


def enabled_sources(conn):
    value = get_setting(conn, "sources_enabled") or ""
    return [s for s in value.split(",") if s in SOURCES]


# ---- Users (TR6) ---------------------------------------------------------------

def _seed_users(conn):
    """Create one demo account per role on a new database."""
    if conn.execute("SELECT 1 FROM users LIMIT 1").fetchone():
        return
    for role in ROLES:
        create_user(conn, role, DEMO_PASSWORD, role)


def create_user(conn, username, password, role):
    username = (username or "").strip()
    if not username or not password:
        raise ValueError("Username and password are required.")
    if role not in ROLES:
        raise ValueError(f"Unknown role: {role}")
    try:
        conn.execute(
            "INSERT INTO users (username, password_hash, role) VALUES (?, ?, ?)",
            (username, generate_password_hash(password), role))
    except sqlite3.IntegrityError:
        raise ValueError(f"User {username} already exists.") from None
    conn.commit()


def authenticate(conn, username, password):
    row = conn.execute("SELECT * FROM users WHERE username = ?", (username,)).fetchone()
    if row and check_password_hash(row["password_hash"], password or ""):
        return {"id": row["id"], "username": row["username"], "role": row["role"]}
    return None


def get_user(conn, user_id):
    row = conn.execute(
        "SELECT id, username, role FROM users WHERE id = ?", (user_id,)).fetchone()
    return dict(row) if row else None


def list_users(conn):
    return [dict(r) for r in conn.execute(
        "SELECT id, username, role FROM users ORDER BY username")]


def delete_user(conn, user_id):
    conn.execute("DELETE FROM users WHERE id = ?", (user_id,))
    conn.commit()


# ---- Collection run log (TR1, TR8, acceptance criterion 1) ----------------------

def start_run(conn, kind):
    cur = conn.execute(
        "INSERT INTO runs (kind, started_at) VALUES (?, ?)", (kind, _now()))
    conn.commit()
    return cur.lastrowid


def finish_run(conn, run_id, status, stored=0, alerts=0, message=""):
    conn.execute(
        "UPDATE runs SET finished_at = ?, status = ?, stored = ?, alerts = ?, message = ?"
        " WHERE id = ?", (_now(), status, stored, alerts, message, run_id))
    conn.commit()


def recent_runs(conn, limit=10):
    return [dict(r) for r in conn.execute(
        "SELECT * FROM runs ORDER BY id DESC LIMIT ?", (limit,))]


def finished_on_time(run):
    """TR8: a nightly cycle must finish before 06:00 on the night it started."""
    end = run.get("finished_at") or ""
    return (run.get("status") == "ok" and end[:10] == run["started_at"][:10]
            and end[11:16] < "06:00")


def nightly_streak(conn):
    """Consecutive nights, up to the latest, with a successful on-time nightly
    cycle (a retry on the same night counts)."""
    nights = {}
    for r in conn.execute("SELECT * FROM runs WHERE kind = 'nightly'"):
        day = r["started_at"][:10]
        nights[day] = nights.get(day, False) or finished_on_time(dict(r))
    streak, expected = 0, None
    for day in sorted(nights, reverse=True):
        d = date.fromisoformat(day)
        if (expected is not None and d != expected) or not nights[day]:
            break
        streak += 1
        expected = d - timedelta(days=1)
    return streak
